def news_verdict(sentiment: float) -> str:
    if sentiment >= 0.6:
        return "좋음"
    if sentiment >= 0.2:
        return "다소 좋음"
    if sentiment <= -0.6:
        return "나쁨"
    if sentiment <= -0.2:
        return "다소 나쁨"
    return "애매"


def news(event_type: str, sentiment: float, what: str) -> Plain:
    name, good, bad = _NEWS.get(event_type, _NEWS["OTHER"])
    verdict = news_verdict(sentiment)
    why = good if sentiment >= 0.2 else bad if sentiment <= -0.2 else "좋다 나쁘다 뚜렷하지 않음"
    return Plain(name, what, verdict, why, "기사 판독(언어 모델)")


def direction(verdict: str) -> str:
    """반응 기록을 나누는 방향: up / down / mixed."""
    return "up" if "좋음" in verdict else "down" if "나쁨" in verdict else "mixed"
