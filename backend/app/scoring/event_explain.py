@dataclass(frozen=True, slots=True)
class Plain:
    kind: str
    """쉬운 이름."""
    what: str
    """무슨 일(한 문장)."""
    verdict: str
    """좋음 / 다소 좋음 / 애매 / 다소 나쁨 / 나쁨."""
    why: str
    source: str
    """방향의 출처: "공시 제목 규칙" 또는 "기사 판독(언어 모델)"."""


def disclosure(keyword: str, subsidiary: bool) -> Plain:
    name, what, verdict, why = _D.get(
        keyword, ("공시", "회사가 공시를 냄", MIXED, "제목을 같이 볼 것")
    )
    if subsidiary:
        # 자회사 일: 회사 주식 수·돈에 바로 닿지 않을 수 있어 방향을 한 단계 누그러뜨린다.
        name = f"자회사 {name}"
        what = f"자회사 쪽 일 — {what}"
        verdict = {GOOD: "다소 좋음", BAD: "다소 나쁨"}.get(verdict, verdict)
        why = f"{why}(자회사 일이라 영향은 작을 수 있음)"
    return Plain(name, what, verdict, why, "공시 제목 규칙")


